#!/usr/bin/env bash
# Install / refresh the single Desktop launcher: Positive Impact Trading.app
# with the trading-themed AppIcon. Bundles an internal Launch.command so the
# unsigned .app can start the repo under ~/Desktop via Terminal (Desktop TCC)
# without leaving a duplicate .command on the Desktop.
#
# Direct resource-fork writes on Desktop often fail (Operation not permitted);
# NSWorkspace.setIcon works under $TMPDIR, then ditto preserves the fork.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ICON_PNG="${REPO_ROOT}/docs/assets/launcher-icon/launcher-icon-1024.png"
ICON_ICNS="${REPO_ROOT}/docs/assets/launcher-icon/PositiveImpactTrading.icns"
DESKTOP="${HOME}/Desktop"
APP_TARGET="${DESKTOP}/Positive Impact Trading.app"
LEGACY_COMMAND="${DESKTOP}/Positive Impact Trading.command"
STARTER="${REPO_ROOT}/scripts/start_trading_morning.sh"

if [[ ! -f "$ICON_PNG" ]]; then
  echo "ERROR: missing icon PNG at ${ICON_PNG}" >&2
  exit 1
fi
if [[ ! -f "$ICON_ICNS" ]]; then
  echo "ERROR: missing icon icns at ${ICON_ICNS}" >&2
  exit 1
fi
if [[ ! -x "$STARTER" ]]; then
  chmod +x "$STARTER" 2>/dev/null || true
fi
if [[ ! -f "$STARTER" ]]; then
  echo "ERROR: missing starter at ${STARTER}" >&2
  exit 1
fi

set_icon_via_tmp() {
  local dest="$1"
  local tmp base
  tmp="$(mktemp -d)"
  base="$(basename "$dest")"
  if [[ -d "$dest" ]]; then
    ditto "$dest" "${tmp}/${base}"
  else
    cp "$dest" "${tmp}/${base}"
    chmod +x "${tmp}/${base}" 2>/dev/null || true
  fi

  local swift_file="${tmp}/seticon.swift"
  cat >"$swift_file" <<SWIFT
import AppKit
import Foundation
let imagePath = "${ICON_PNG}"
let targetPath = "${tmp}/${base}"
guard let image = NSImage(contentsOfFile: imagePath) else {
    fputs("failed to load \(imagePath)\n", stderr)
    exit(1)
}
let ok = NSWorkspace.shared.setIcon(image, forFile: targetPath, options: [])
if !ok {
    fputs("NSWorkspace.setIcon failed for \(targetPath)\n", stderr)
    exit(1)
}
print("setIcon ok")
SWIFT
  /usr/bin/swift "$swift_file"

  if [[ -d "$dest" ]]; then
    rm -rf "$dest"
  fi
  ditto "${tmp}/${base}" "$dest"
  /usr/bin/SetFile -a C "$dest" 2>/dev/null || true
  rm -rf "$tmp"
  echo "icon applied: ${dest}"
}

install_app_bundle() {
  local app="$1"
  rm -rf "$app"
  mkdir -p "${app}/Contents/MacOS" "${app}/Contents/Resources"
  cp "$ICON_ICNS" "${app}/Contents/Resources/AppIcon.icns"

  # Internal helper (NOT on Desktop): Terminal runs this with Desktop TCC.
  cat >"${app}/Contents/Resources/Launch.command" <<EOF
#!/bin/bash
# Bundled morning launcher — opened by the .app via /usr/bin/open.
# Generated by scripts/apply_launcher_icon.sh — edit the repo script, not this file.
set -euo pipefail
cd "${REPO_ROOT}" || exit 1
LOG_DIR="\${TMPDIR:-/tmp}/positive-impact-trading"
mkdir -p "\$LOG_DIR"
"${STARTER}" 2>&1 | tee -a "\$LOG_DIR/launcher.log"
exit "\${PIPESTATUS[0]}"
EOF
  chmod +x "${app}/Contents/Resources/Launch.command"

  cat >"${app}/Contents/Info.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key>
  <string>Positive Impact Trading</string>
  <key>CFBundleDisplayName</key>
  <string>Positive Impact Trading</string>
  <key>CFBundleIdentifier</key>
  <string>com.positiveimpact.trading.launcher</string>
  <key>CFBundleVersion</key>
  <string>1.1</string>
  <key>CFBundleShortVersionString</key>
  <string>1.1</string>
  <key>CFBundlePackageType</key>
  <string>APPL</string>
  <key>CFBundleExecutable</key>
  <string>PositiveImpactTrading</string>
  <key>CFBundleIconFile</key>
  <string>AppIcon</string>
  <key>LSMinimumSystemVersion</key>
  <string>12.0</string>
  <key>NSHighResolutionCapable</key>
  <true/>
</dict>
</plist>
PLIST

  # IMPORTANT: the repo lives under ~/Desktop. Unsigned .apps launched by Finder
  # do NOT get Desktop Folder TCC, so a direct `exec` of the starter fails with
  # "Operation not permitted". Opening a bundled Launch.command (or Terminal)
  # works because Terminal typically already has Desktop access.
  local bundled_command="${app}/Contents/Resources/Launch.command"
  cat >"${app}/Contents/MacOS/PositiveImpactTrading" <<EXEC
#!/bin/bash
set -euo pipefail
STARTER='${STARTER}'
BUNDLED_COMMAND='${bundled_command}'
LOG_DIR="\${TMPDIR:-/tmp}/positive-impact-trading"
LOG="\${LOG_DIR}/launcher.log"
mkdir -p "\$LOG_DIR"
stamp() { date '+%Y-%m-%d %H:%M:%S %Z'; }

if [[ ! -f "\$STARTER" ]]; then
  echo "\$(stamp) missing starter: \$STARTER" >>"\$LOG"
  /usr/bin/osascript -e "display alert \\"Positive Impact Trading\\" message \\"Missing starter script:\\n\$STARTER\\n\\nPull/checkout master and re-run scripts/install_desktop_launcher.sh\\" as critical" >/dev/null 2>&1 || true
  exit 1
fi

# 1) Preferred: open bundled Launch.command so Terminal runs it with Desktop access.
if [[ -x "\$BUNDLED_COMMAND" ]]; then
  echo "\$(stamp) opening bundled Launch.command via LaunchServices" >>"\$LOG"
  /usr/bin/open "\$BUNDLED_COMMAND"
  exit 0
fi

# 2) Fallback: ask Terminal to exec the starter (needs Automation permission once).
echo "\$(stamp) bundled Launch.command missing — falling back to Terminal do script" >>"\$LOG"
if /usr/bin/osascript <<OSA >>"\$LOG" 2>&1
tell application "Terminal"
  activate
  do script "exec '\$STARTER'"
end tell
OSA
then
  exit 0
fi

echo "\$(stamp) Terminal Automation failed" >>"\$LOG"
/usr/bin/osascript -e "display alert \\"Positive Impact Trading\\" message \\"Could not start. Re-run scripts/install_desktop_launcher.sh, then right-click the app → Open. Log:\\n\$LOG\\" as critical" >/dev/null 2>&1 || true
open -t "\$LOG" >/dev/null 2>&1 || true
exit 1
EXEC
  chmod +x "${app}/Contents/MacOS/PositiveImpactTrading"
  xattr -cr "$app" 2>/dev/null || true
  set_icon_via_tmp "$app"
  /System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister -f "$app" >/dev/null 2>&1 || true
  echo "app installed: ${app}"
}

# Remove legacy Desktop .command duplicate (single launcher = .app only).
if [[ -e "$LEGACY_COMMAND" ]]; then
  rm -f "$LEGACY_COMMAND"
  echo "removed legacy Desktop .command: ${LEGACY_COMMAND}"
fi

install_app_bundle "$APP_TARGET"
