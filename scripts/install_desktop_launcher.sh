#!/usr/bin/env bash
# Install a double-clickable Desktop shortcut for morning trading start.
# Writes Positive Impact Trading.command, then applies the custom icon and
# installs Positive Impact Trading.app (AppIcon.icns + same starter).
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DESKTOP="${HOME}/Desktop"
SHORTCUT="${DESKTOP}/Positive Impact Trading.command"
STARTER="${REPO_ROOT}/scripts/start_trading_morning.sh"
APPLY="${REPO_ROOT}/scripts/apply_launcher_icon.sh"

chmod +x "$STARTER" \
  "${REPO_ROOT}/scripts/install_desktop_launcher.sh" \
  "$APPLY"

# Build the .command under $TMPDIR, then ditto to Desktop (keeps later icon fork intact).
TMP="$(mktemp -d)"
TMP_SHORTCUT="${TMP}/Positive Impact Trading.command"
cat >"$TMP_SHORTCUT" <<EOF
#!/bin/bash
# Double-click from Finder → morning stack (IB Gateway + cockpit).
# Generated by scripts/install_desktop_launcher.sh — edit the repo script, not this file.
cd "${REPO_ROOT}" || exit 1
LOG_DIR="\${TMPDIR:-/tmp}/positive-impact-trading"
mkdir -p "\$LOG_DIR"
"${STARTER}" 2>&1 | tee -a "\$LOG_DIR/launcher.log"
exit "\${PIPESTATUS[0]}"
EOF
chmod +x "$TMP_SHORTCUT"
ditto "$TMP_SHORTCUT" "$SHORTCUT"
rm -rf "$TMP"

# Clear quarantine so Finder does not block first open (best-effort).
xattr -d com.apple.quarantine "$SHORTCUT" 2>/dev/null || true

# Custom trading icon on .command + Desktop .app with AppIcon.icns
"$APPLY"

echo
echo "Installed:"
echo "  ${SHORTCUT}"
echo "  ${DESKTOP}/Positive Impact Trading.app"
echo "Prefer the .app on Desktop (custom chart icon). Double-click to start."
echo "If macOS warns on first open: right-click → Open."
